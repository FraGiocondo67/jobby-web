type LanguageContextValue = {
  lang: string
  setLang: (lang: string) => void
  t: (key: string) => string
}

const LanguageContext = createContext<LanguageContextValue>({
  lang: 'it',
  setLang: () => {},
  t: (key: string) => key,
})

export function useLanguage() {
  return useContext(LanguageContext)
}

const STORAGE_KEY = 'jobby_lang'

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState('it')
  const loadedFromServer = useRef(false)

  useEffect(() => {
    // 1) preferenza locale (funziona anche prima del login, es. su /login)
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY)
      if (stored && TRANSLATIONS[stored]) setLangState(stored)
    } catch {}

    // 2) se loggato, la preferenza salvata su users.preferred_lang e' la fonte
    // di verita' condivisa con l'App — la applichiamo se presente.
    supabase.auth.getSession().then(async ({ data: { session } }) => {
      if (!session) return
      const { data } = await supabase
        .from('users')
        .select('preferred_lang')
        .eq('auth_id', session.user.id)
        .maybeSingle()
      if (data?.preferred_lang && TRANSLATIONS[data.preferred_lang]) {
        loadedFromServer.current = true
        setLangState(data.preferred_lang)
        try { window.localStorage.setItem(STORAGE_KEY, data.preferred_lang) } catch {}
      }
    })
  }, [])

  const setLang = useCallback((newLang: string) => {
    if (!TRANSLATIONS[newLang]) return
    setLangState(newLang)
    try { window.localStorage.setItem(STORAGE_KEY, newLang) } catch {}
  }, [])

  const t = useCallback((key: string) => {
    return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? TRANSLATIONS.it[key] ?? key
  }, [lang])

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  )
}
